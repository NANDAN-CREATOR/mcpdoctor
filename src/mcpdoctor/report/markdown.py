from __future__ import annotations

from mcpdoctor.models import Report, Severity

_EMOJI = {Severity.CRITICAL: "🟥", Severity.HIGH: "🟧", Severity.MEDIUM: "🟨", Severity.LOW: "🟦", Severity.INFO: "⬜"}


def _esc(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(report: Report, *, max_findings: int = 40) -> str:
    sc = report.scores
    srv = report.server
    lines = [f"## MCPDoctor report: `{report.target}`", ""]
    lines.append(f"**Score: {sc.get('overall', '?')}/100 (grade {sc.get('grade', '?')})** - "
                 f"{len(report.tools)} tool(s), {report.evaluation.get('calls_made', 0)} tool call(s), "
                 f"{report.duration_s:.1f}s. Server: `{srv.name} {srv.version}`".rstrip() + "")
    lines.append("")
    if sc:
        lines.append("| Security | Quality | Reliability |")
        lines.append("|---|---|---|")
        cells = []
        for name in ("security", "quality", "reliability"):
            c = sc["categories"][name]
            cells.append(f"{c['score']} ({c['grade']})" if c["assessed"] else "not tested")
        lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
        for cap in sc.get("caps", []):
            lines.append(f"> ⚠️ {cap}")
        if sc.get("caps"):
            lines.append("")

    counts = report.counts()
    lines.append("**Findings:** " + (", ".join(f"{counts[s.value]} {s.value}" for s in reversed(list(Severity))
                                               if counts[s.value]) or "none"))
    lines.append("")
    findings = report.by_severity()
    if findings:
        lines.append("| Severity | Rule | Tool | Finding |")
        lines.append("|---|---|---|---|")
        for f in findings[:max_findings]:
            lines.append(f"| {_EMOJI[f.severity]} {f.severity.value} | `{f.rule_id}` | "
                         f"{('`' + f.tool + '`') if f.tool else ''} | {_esc(f.message)[:260]} |")
        if len(findings) > max_findings:
            lines.append(f"| | | | ... and {len(findings) - max_findings} more (see the full report) |")
        lines.append("")
        top = [f for f in findings if f.severity.rank >= Severity.HIGH.rank][:5]
        if top:
            lines.append("<details><summary>How to fix the most serious findings</summary>\n")
            for f in top:
                lines.append(f"- **{f.rule_id} {f.title}**{(' (`' + f.tool + '`)') if f.tool else ''}: {f.fix}")
            lines.append("\n</details>\n")

    ag = report.evaluation.get("agent")
    if ag:
        lines.append(f"**Agent evaluation** ({ag['provider']}/{ag['model']}): tool selection "
                     f"{ag['tool_selection_accuracy']}, argument validity {ag['argument_validity']}, "
                     f"about {ag['avg_prompt_tokens_per_request']} prompt tokens per request.\n")

    lines.append("<details><summary>What was tested</summary>\n")
    lines.append("| Check | Status | Detail |")
    lines.append("|---|---|---|")
    for c in report.coverage:
        lines.append(f"| {c.name} | {c.status} | {_esc(c.detail)[:200]} |")
    lines.append("\n</details>\n")
    lines.append(f"<sub>Generated by MCPDoctor {report.version}. A clean report is not a proof of safety: see the "
                 "coverage table for what was not tested.</sub>")
    return "\n".join(lines) + "\n"
